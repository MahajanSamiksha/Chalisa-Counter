// Release signing credentials, read from a gitignored file so they never enter version control.
// Absent on a fresh clone and in CI for pull requests, which is fine: debug builds and unit tests
// do not need them, and the release build falls back to unsigned rather than failing the whole
// configuration phase.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use(::load)
    }
}
val hasReleaseSigning = keystoreProperties.getProperty("storeFile").isNullOrBlank().not()

android {
    namespace = "com.hanumanchalisa.counter"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.hanumanchalisa.counter"
        minSdk = 24
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Signed only when keystore.properties is present; otherwise the APK comes out
            // unsigned and Android will refuse to install it. Never fall back to the debug
            // signing config here — the debug key is public, so anyone could forge an update.
            signingConfig = if (hasReleaseSigning) signingConfigs.getByName("release") else null

            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }

    kotlin {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_11)
        }
    }

    buildFeatures {
        compose = true
    }
}

